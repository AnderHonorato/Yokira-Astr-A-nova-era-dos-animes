CREATE TABLE PercursoEpisodio (
 usuarioId TEXT NOT NULL REFERENCES Usuario(id) ON DELETE CASCADE ON UPDATE CASCADE,
 episodioId TEXT NOT NULL REFERENCES Episodio(id) ON DELETE CASCADE ON UPDATE CASCADE,
 cobertura INTEGER NOT NULL DEFAULT 0, validado BOOLEAN NOT NULL DEFAULT false,
 PRIMARY KEY(usuarioId, episodioId)
);
CREATE TABLE PulsoJornada (
 usuarioId TEXT PRIMARY KEY NOT NULL REFERENCES Usuario(id) ON DELETE CASCADE ON UPDATE CASCADE,
 episodioId TEXT NOT NULL, posicao INTEGER NOT NULL, recebidoEm DATETIME NOT NULL
);
CREATE TABLE ConquistaJornada (
 usuarioId TEXT NOT NULL REFERENCES Usuario(id) ON DELETE CASCADE ON UPDATE CASCADE,
 chave TEXT NOT NULL, criadoEm DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(usuarioId, chave)
);
